import assert from 'node:assert/strict'
import { post } from './handset-auth.mjs'
import { messagesFixture } from './handset-messages.mjs'

export async function messageJourney({runtime,page,context,cookie,proof,click}) {
 await page.goto(runtime.origin+'/app/cases');await page.getByRole('navigation',{name:'Handset',exact:true}).getByRole('link',{name:'Messages',exact:true}).click(); await proof('messages-empty')
 assert.match(await page.locator('main').innerText(),/No conversations yet/)
 const f=await messagesFixture(runtime),headers={cookie}
 await f.incoming('Please help with my order',{NumMedia:'1',MediaUrl0:`https://api.twilio.com/2010-04-01/Accounts/${f.source.account}/Messages/synthetic-handset-1880/Media/synthetic-handset-1881`,MediaContentType0:'image/jpeg'})
 const snapshot=async()=>await (await runtime.request('/api/handset/messages',{headers})).json()
 const thread=(await snapshot()).threads.find(t=>t.peer===f.recipient)
 assert.ok(thread)
 await page.goto(runtime.origin+'/app/messages?thread='+encodeURIComponent(thread.id)); await proof('messages-inbox')
 assert.match(await page.locator('main').innerText(),/Please help with my order/)
 await click('Claim conversation'); await proof('messages-claimed')
 await page.goto(runtime.origin+'/app/messages/settings');await proof('messages-settings-empty')
 await page.getByLabel('Snippet name',{exact:true}).fill('Order follow-up')
 await page.getByLabel('Snippet text',{exact:true}).fill('We will check your order and follow up.')
 await click('Save snippet')
 await page.getByLabel('Recipient',{exact:true}).fill(f.recipient)
 await page.getByLabel('Evidence of explicit permission',{exact:true}).fill('Customer requested a customer-care text during the call')
 await page.getByLabel('Permission expires at (UTC)',{exact:true}).fill(new Date(f.now+30*86400000).toISOString().slice(0,16))
 await page.getByRole('checkbox',{name:'I verified explicit permission for customer-care texts'}).check()
 await click('Record permission');await proof('messages-settings-populated')
 await page.goto(runtime.origin+'/app/messages?thread='+encodeURIComponent(thread.id))
 await page.getByLabel('Due at (UTC)',{exact:true}).fill(new Date(f.now+60000).toISOString().slice(0,16))
 await click('Create scheduled draft'); await proof('messages-draft')
 assert.match(await page.locator('main').innerText(),/We will check your order and follow up/)
 await page.getByRole('checkbox',{name:/I reviewed and approve the exact scheduled message/}).check()
 await click('Queue exact message'); await proof('messages-queued')
 assert.match(await page.locator('main').innerText(),/queued/)
 await runtime.setTime(f.now+120000)
 await click('Send queued message');await proof('messages-accepted')
 assert.equal((await snapshot()).jobs[0].carrier_state,'unconfirmed')
 const receipt=f.receiver.sent[0].message;receipt.status='delivered';f.source.resource('Messages',receipt.sid,receipt)
 await click('Refresh delivery status');await proof('messages-delivered')
 assert.equal((await snapshot()).jobs[0].carrier_state,'delivered')
 const failedDraft=await f.queued({dueAt:f.now+120000,body:'Revisaremos su pedido y le avisaremos.'})
 const failedSend=(await f.write('/jobs/'+failedDraft.id+'/dispatch',{revision:failedDraft.revision},200)).job
 const failedReceipt=f.receiver.sent.at(-1).message;failedReceipt.status='undelivered';f.source.resource('Messages',failedReceipt.sid,failedReceipt)
 assert.equal((await f.write('/jobs/'+failedSend.id+'/refresh',{},200)).job.carrier_state,'failed')
 await page.reload();await proof('messages-failed')
 const uncertainDraft=await f.queued({dueAt:f.now+120000});f.receiver.drop=true
 assert.equal((await f.write('/jobs/'+uncertainDraft.id+'/dispatch',{revision:uncertainDraft.revision},200)).job.state,'uncertain')
 await page.reload();await proof('messages-uncertain')
 await click('Record HappyToHelp custody'); await proof('messages-custody')
 assert.match(await page.locator('main').innerText(),/HappyToHelp/i)
 await click('Reclaim for handset')
 // A stale revision is refused while the visible form retains its submitted values.
 const current=(await snapshot()).threads.find(t=>t.id===thread.id)
 const changed=await post(runtime,`/api/handset/messages/threads/${thread.id}/claim`,{revision:current.revision},headers)
 assert.ok(changed.ok,await changed.clone().text())
 await click('Claim conversation'); await page.getByRole('alert').waitFor(); await proof('messages-denied')
 assert.match(await page.getByRole('alert').innerText(),/Submitted revision/)
 await f.incoming('STOP')
 await page.goto(runtime.origin+'/app/messages?thread='+encodeURIComponent(thread.id)); await proof('messages-suppressed')
 assert.match(await page.locator('main').innerText(),/Suppressed/)
 for(let i=0;i<201;i++)await f.incoming('Order progress '+i,{Timestamp:new Date(f.now+i).toISOString()})
 await page.reload();assert.match(await page.locator('main').innerText(),/Order progress 200/);await proof('messages-latest-history')
 await page.getByRole('link',{name:'Older messages',exact:true}).click()
 assert.match(await page.locator('main').innerText(),/Order progress 0/);await proof('messages-older-history')
 const {groupsFixture}=await import('./handset-message-groups.mjs'),grouped=await groupsFixture(runtime,{authorize:false})
 const [groupCookieName,...groupCookieValue]=grouped.source.cookie.split('=')
 await context.clearCookies();await context.addCookies([{name:groupCookieName,value:groupCookieValue.join('='),url:runtime.origin,secure:true,httpOnly:true,sameSite:'Lax'}])
 await page.goto(runtime.origin+'/app/messages/settings')
 await page.getByRole('combobox',{name:'Business source',exact:true}).selectOption(grouped.source.source.id)
 await page.getByLabel('Conversation service SID',{exact:true}).fill('synthetic-handset-1871')
 await page.getByLabel('Conversation SID',{exact:true}).fill('synthetic-handset-1872')
 await page.getByRole('checkbox',{name:'I authorize incoming metadata for this exact group conversation',exact:true}).check()
 await click('Authorize group metadata');await proof('messages-group-settings')
 const groupResponse=await grouped.receive();assert.equal(groupResponse.status,200,await groupResponse.clone().text())
 const groupId=(await groupResponse.json()).threadId
 await page.goto(runtime.origin+'/app/messages?thread='+groupId);await proof('messages-group-metadata')
 assert.match(await page.locator('main').innerText(),/Both of us can meet/)
 await page.goto(runtime.origin+'/app/messages/settings');await click('Revoke group source');await proof('messages-group-revoked-settings')
 const withdrawn=await page.goto(runtime.origin+'/app/messages?thread='+groupId);assert.equal(withdrawn.status(),403)
 await page.getByRole('alert').waitFor();await proof('messages-group-revoked')
 assert.equal((await runtime.request('/api/handset/messages')).status,401)
 assert.equal(await page.getByRole('button').evaluateAll(buttons=>buttons.every(b=>b.textContent.trim().length>2)),true)
 void context
}
