import assert from 'node:assert/strict'
import { post } from './handset-auth.mjs'
import { flowRoleFixture } from './handset-flow-access.mjs'

export async function flowRoleJourney({runtime,page,proof,cookie,q}){
 const as=async cookie=>{const [name,...rest]=cookie.split('=');await page.context().clearCookies();await page.context().addCookies([{name,value:rest.join('='),url:runtime.origin,secure:true,httpOnly:true,sameSite:'Lax'}])}
 const click=async(form,name)=>{await form.getByRole('button',{name,exact:true}).click();await page.waitForLoadState('load')}
 const f=await flowRoleFixture(runtime,q)
 await as(cookie);await page.goto(runtime.origin+'/app/flows')
 await page.getByRole('link',{name:'Role settings',exact:true}).click()
 const create=page.locator('form[action="/app/prompts/access"]')
 await create.getByLabel('Role name',{exact:true}).fill(f.roleInput.name)
 await create.getByLabel('Edit greeting drafts',{exact:true}).uncheck()
 for(const name of ['Read selected flows','Edit flow drafts','Test selected flows','Austin reception access','I approve this exact role and scope'])await create.getByLabel(name,{exact:true}).check()
 await click(create,'Create custom role')
 const roles=await (await runtime.request(f.access,{headers:q.headers})).json(),role=roles.roles.find(r=>r.name===f.roleInput.name)
 assert.deepEqual(JSON.parse(role.flow_ids),[f.allowed.flowId])
 const assign=page.locator(`form[action="/app/prompts/access/${role.id}/assign"]`)
 await assign.getByLabel('Member',{exact:true}).selectOption({label:'Elliot Brooks'});await assign.getByRole('checkbox').check();await click(assign,'Assign custom role')
 assert.match(await page.locator('main').innerText(),/Elliot Brooks · active/);await proof('flow-role-owner-assigned')
 await as(f.member.cookie);await page.goto(runtime.origin+'/app/flows')
 assert.deepEqual(await page.locator('main li a').allTextContents(),['Austin reception access · Version 1'])
 assert.equal(await page.getByRole('button',{name:'Save immutable draft',exact:true}).count(),0)
 await proof('flow-role-scoped-list')
 assert.equal((await page.goto(runtime.origin+'/app/flows/'+f.foreign.id)).status(),404);await proof('flow-role-foreign-refused')
 await page.goto(runtime.origin+'/app/flows/'+f.allowed.id)
 assert.deepEqual(await page.locator('select[name="queueId0"] option').allTextContents(),['None','Sales / Ventas'])
 assert.equal(await page.getByRole('checkbox',{name:'Include Mara Patel in group 1',exact:true}).count(),0)
 assert.equal(await page.getByRole('button',{name:'Publish this tested version',exact:true}).count(),0)
 await page.getByLabel('Flow name',{exact:true}).fill('Austin staff revision');await click(page,'Save immutable draft')
 const draft=new URL(page.url()).pathname.split('/').at(-1)
 await click(page,'Test sales');await proof('flow-role-staff-tested-draft')
 const evaluate=page.locator('form').filter({has:page.getByRole('button',{name:'Evaluate native scenario',exact:true})})
 await evaluate.getByLabel('Evaluation instant',{exact:true}).fill('2026-10-27T18:00:00Z')
 await evaluate.getByRole('checkbox',{name:'Eligible member Rosa García',exact:true}).check();await click(evaluate,'Evaluate native scenario')
 assert.match(await page.locator('main').innerText(),/Selected group members: Rosa García/);await proof('flow-role-staff-evaluated')
 assert.equal((await f.actorPost(`${f.base}/${draft}/publish`,{revision:0,confirm:'approve this exact tested flow version'})).status,403)
 await as(cookie);await page.goto(runtime.origin+'/app/flows/'+draft)
 await page.getByRole('checkbox',{name:/I approve this exact tested flow version/}).check();await click(page,'Publish this tested version');await proof('flow-role-owner-exact-publication')
 const catalog=await (await runtime.request(f.base,{headers:f.headers})).json()
 assert.deepEqual(catalog.publications.map(p=>[p.version_id,p.revision,p.approved_by]),[[draft,1,q.english]])
 await page.goto(runtime.origin+'/app/prompts/access')
 const revise=page.locator(`form[action="/app/prompts/access/${role.id}"]`)
 await revise.getByLabel('Test selected flows',{exact:true}).uncheck();await revise.getByLabel('I approve this exact role and scope',{exact:true}).check();await click(revise,'Save role revision')
 assert.match(await page.locator('main').innerText(),/Elliot Brooks · suspended/);await proof('flow-role-owner-suspended')
 await as(f.member.cookie);assert.equal((await page.goto(runtime.origin+'/app/flows')).status(),403);await proof('flow-role-withdrawn')
 assert.equal((await post(runtime,'/auth/operator/status',{operatorId:f.personId,status:'inactive'},q.headers)).status,200)
 assert.equal((await f.actorPost(`${f.base}/${draft}/test`,{path:['sales']})).status,401)
 await page.goto(runtime.origin+'/app/flows');await page.waitForURL(/\/signin\?/);await proof('flow-role-person-removed')
 await as(cookie)
}
