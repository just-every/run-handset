import assert from 'node:assert/strict'
import { localDateTime } from './handset-browser-time.mjs'
import { dialerFixture } from './handset-dialer.mjs'

export async function dialerJourney({runtime,page,proof}){
 const base=runtime.origin+'/app/dialer'
 const submit=async form=>{await form.getByRole('button').click();await page.waitForLoadState('load')}
 const form=path=>page.locator(`form[action="/app/dialer/${path}"]`)
 await page.goto(base);await proof('dialer-empty')
 const f=await dialerFixture(runtime),list=await f.makeList({count:2,mode:'preview',check:false,name:'Austin appointment callbacks / Recordatorios'})
 await page.goto(base+'?listId='+list.id);await proof('dialer-reviewed-audience')
 const details=page.locator('details').filter({has:page.locator('summary').filter({hasText:'Verify Alicia Torres'})})
 await details.locator('summary').click()
 const check=form('lists/'+list.id+'/recipients/0/verify')
 await check.getByLabel('Current consent verification evidence',{exact:true}).selectOption(list.recipients[0].consentId)
 for(const scope of ['Company','National','State','Campaign'])await check.getByLabel(scope+' suppression check',{exact:true}).selectOption('clear')
 await check.getByLabel('Exact verified customer purpose',{exact:true}).fill(f.purpose)
 await check.getByLabel('Verification expires, within one day (UTC)',{exact:true}).fill(localDateTime(Date.now()+600000))
 await check.getByRole('checkbox',{name:'Preview',exact:true}).check()
 await check.locator('input[name="confirm"]').check();await submit(check)
 await proof('dialer-recipient-verified')
 const start=form('lists/'+list.id+'/sessions')
 await start.getByLabel('Session dialing mode',{exact:true}).selectOption('preview')
 await start.locator('input[name="confirm"]').check();await submit(start)
 const run=(await f.read()).sessions[0]
 assert.equal(run.mode,'preview');assert.equal(run.cursor,0)
 await page.goto(base+'?listId='+list.id);await proof('dialer-ready-required')
 const premature=form('sessions/'+run.id+'/launch')
 await premature.getByLabel('Unique launch reference',{exact:true}).fill(f.next())
 await premature.getByLabel('Exact preview recipient',{exact:true}).selectOption(list.recipients[0].recipient)
 await premature.locator('input[name="confirm"]').check();await submit(premature)
 assert.equal((await f.read()).sessions.find(s=>s.id===run.id).state,'paused')
 assert.ok(runtime.sourceRequests.every(r=>r.method==='GET'),'without a waiting agent the console creates no provider call')
 await proof('dialer-held-without-waiting-agent')
 const waiting=await f.ready(f.q.english,{persist:false})
 const ready=form('ready')
 await ready.getByLabel('Waiting human agent and approved route',{exact:true}).selectOption(f.q.english)
 await ready.getByLabel('Exact source for this media route',{exact:true}).selectOption(f.source.id)
 await ready.getByLabel('Provider conference SID',{exact:true}).fill(waiting.conferenceSid)
 await ready.getByLabel('Exact provider conference friendly name',{exact:true}).fill(waiting.conferenceName)
 await ready.getByLabel('Connected agent Call SID',{exact:true}).fill(waiting.agentCallSid)
 await ready.getByLabel('Waiting-agent evidence expires, within 90 seconds (UTC)',{exact:true}).fill(localDateTime(Date.now()+80000))
 await ready.locator('input[name="confirm"]').check();await submit(ready)
 await page.goto(base+'?listId='+list.id);await proof('dialer-waiting-agent-verified')
 await submit(form('sessions/'+run.id+'/resume'))
 const call=f.prepare(list),launch=form('sessions/'+run.id+'/launch')
 await launch.getByLabel('Unique launch reference',{exact:true}).fill(f.next())
 await launch.getByLabel('Exact preview recipient',{exact:true}).selectOption(list.recipients[0].recipient)
 await launch.locator('input[name="confirm"]').check();await submit(launch)
 let attempt=(await f.read()).attempts[0]
 assert.ok(attempt.provider_sid);assert.equal(attempt.recipient,list.recipients[0].recipient)
 await proof('dialer-provider-accepted')
 await f.connect(attempt,call)
 await page.goto(base+'?listId='+list.id);await proof('dialer-bridge-observed')
 await submit(form('sessions/'+run.id+'/pause'))
 const held=await f.read();assert.equal(held.sessions.find(s=>s.id===run.id).state,'paused');assert.equal(held.attempts.find(a=>a.id===attempt.id).state,'active')
 await proof('dialer-paused-connected')
 await new Promise(resolve=>setTimeout(resolve,1100))
 const started=Date.parse(call.data.start_time),end=new Date().toUTCString()
 f.updateCall(call,{status:'completed',end_time:end,duration:String(Math.floor((Date.parse(end)-started)/1000))})
 const outcome=await f.callback(attempt,call);assert.equal(outcome.status,200,await outcome.clone().text())
 await page.goto(base+'?listId='+list.id)
 const disposition=form('attempts/'+attempt.id+'/disposition')
 await disposition.getByLabel('Observed outcome',{exact:true}).selectOption('human_connected')
 await disposition.getByLabel('Observation and notes',{exact:true}).fill('Controlled appointment callback reached Alicia; requested booking remains separately owned.')
 await disposition.locator('input[name="confirm"]').check();await submit(disposition)
 assert.equal((await f.read()).attempts.find(a=>a.id===attempt.id).disposition,'human_connected')
 await proof('dialer-observed-disposition')
 await submit(form('lists/'+list.id+'/revoke'));await proof('dialer-list-revoked')
 assert.ok((await f.read()).lists.find(l=>l.id===list.id).revoked_at)
 await submit(form('sessions/'+run.id+'/resume'));await page.getByRole('alert').waitFor();await proof('dialer-stale-approval-refusal')
}
