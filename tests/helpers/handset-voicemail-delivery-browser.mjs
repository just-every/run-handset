import assert from 'node:assert/strict'
import { voicemailDeliveryFixture } from './handset-voicemail-delivery.mjs'

export async function voicemailDeliveryBrowserJourney({runtime,page,context,proof}){
 const f=await voicemailDeliveryFixture(runtime),a=await f.item(30),settings='/app/voicemail/settings/'+f.box.id+'/delivery'
 const authenticate=async(cookie)=>{const [name,...value]=cookie.split('=');await context.clearCookies();await context.addCookies([{name,value:value.join('='),url:runtime.origin,secure:true,httpOnly:true,sameSite:'Lax'}])}
 const submit=async(name)=>{await page.getByRole('button',{name,exact:true}).click();await page.waitForLoadState('load')}
 await authenticate(f.cookie)
 await page.goto(runtime.origin+'/app/voicemail/'+f.box.id)
 await page.getByRole('link',{name:'Delivery settings',exact:true}).click()
 assert.equal(new URL(page.url()).pathname,settings)
 assert.ok((await page.locator('main').innerText()).includes('Nothing sends'))
 assert.ok((await page.locator('main').innerText()).includes('cannot recall'))
 assert.ok((await page.locator('main').innerText()).includes('retain and forward'))
 await page.getByLabel('Recipient',{exact:true}).selectOption({label:'Export reviewer · '+[f.personId,'example.test'].join('@')})
 assert.ok((await page.getByLabel('Recipient',{exact:true}).locator('option:checked').innerText()).includes([f.personId,'example.test'].join('@')))
 await page.getByLabel('Delivery mode',{exact:true}).selectOption('attachment_text')
 assert.equal(await page.getByLabel('Delivery mode',{exact:true}).inputValue(),'attachment_text')
 await page.getByRole('checkbox',{name:'I approve this exact recipient and mode with separate email custody',exact:true}).check()
 await proof('voicemail-delivery-choice')
 await submit('Save delivery mode')
 assert.match(await page.locator('main').innerText(),/Audio attachment plus supplied text · Enabled · Revision 1/)
 await proof('voicemail-delivery-active')
 const data=await f.get(f.base+'/delivery'),setting=data.settings[0]
 // The native item door queues the exact saved setting, never arbitrary content.
 await page.goto(runtime.origin+'/app/voicemail/'+f.box.id+'/items/'+a.item.id)
 await page.getByText('Queue reviewed delivery',{exact:true}).click()
 await page.getByLabel('Reviewed recipient and mode',{exact:true}).selectOption(setting.id)
 const due=new Date(Date.now()+60000).toISOString().slice(0,16)
 await page.getByLabel('Send at (UTC)',{exact:true}).fill(due)
 await page.getByRole('checkbox',{name:'Queue this exact voicemail delivery',exact:true}).check()
 await submit('Queue voicemail email')
 const queued=(await f.get(f.base+'/delivery')).jobs[0];assert.equal(queued.state,'queued')
 await runtime.scheduled(Date.now()+120000)
 const mail=runtime.mails.at(-1);assert.deepEqual(Buffer.from(mail.attachments[0].content,'base64'),a.bytes)
 await page.goto(runtime.origin+settings)
 assert.match(await page.locator('main').innerText(),/accepted/)
 assert.match(await page.locator('main').innerText(),/never confirmed inbox receipt/)
 await page.getByLabel('Required delivery policy',{exact:true}).selectOption('1')
 await submit('Save delivery policy')
 assert.deepEqual(await page.getByLabel('Delivery mode',{exact:true}).locator('option').evaluateAll(options=>options.map(o=>o.value)),['','link'])
 await page.getByLabel('Recipient',{exact:true}).selectOption({label:'Export reviewer · '+[f.personId,'example.test'].join('@')})
 await page.getByLabel('Delivery mode',{exact:true}).selectOption('link')
 await page.getByRole('checkbox',{name:'I approve this exact recipient and mode with separate email custody',exact:true}).check()
 await submit('Save delivery mode')
 const b=await f.item(31),linkSetting=(await f.get(f.base+'/delivery')).settings[0],job=await f.queue(b,linkSetting)
 await runtime.scheduled()
 const link='/app/voicemail/links/'+job.job.link_id
 assert.equal(runtime.mails.at(-1).attachments,undefined)
 await page.goto(runtime.origin+settings);await proof('voicemail-link-only-policy')
 await authenticate(f.recipient.cookie);await page.goto(runtime.origin+link)
 assert.ok((await page.locator('main').innerText()).includes('Please call on Tuesday.'))
 const audio=page.getByLabel('Approved voicemail',{exact:true})
 await audio.evaluate(async element=>{await element.play();element.pause()})
 assert.equal(await audio.evaluate(element=>element.duration),1,'the approved native bytes are playable')
 await proof('voicemail-authenticated-link')
 await authenticate(f.cookie);await page.goto(runtime.origin+settings)
 await submit('Revoke authenticated link')
 await authenticate(f.recipient.cookie)
 assert.equal((await page.goto(runtime.origin+link)).status(),403)
 assert.equal((await page.locator('main').innerText()).includes('Please call on Tuesday.'),false)
 await proof('voicemail-link-revoked')
 await authenticate(f.cookie)
}
