import assert from 'node:assert/strict'
import { openHandset } from './handset-worker.mjs'
import { createEdges } from './handset-edges.mjs'
import { callReportsFixture,callReportNow } from './handset-call-reports.mjs'
import { metricConfig } from './handset-metrics.mjs'
import { callReportStart } from './handset-call-reports.mjs'
import { post,signIn } from './handset-auth.mjs'

export async function callReportsBrowserJourney({page,context,proof,click}){
 const edges=createEdges(),runtime=await openHandset({twilio:true,edges,clockTime:callReportNow})
 const signin=async cookie=>{const [name,...value]=cookie.split('=');await context.clearCookies();await context.addCookies([{name,value:value.join('='),url:runtime.origin,secure:true,httpOnly:true,sameSite:'Lax'}])}
 const metric=async name=>page.locator('dt').filter({hasText:new RegExp('^'+name+'$')}).locator('xpath=following-sibling::dd[1]').innerText()
 try{
  const f=await callReportsFixture(runtime,edges)
  await signin(f.source.cookie)
  const root=runtime.origin+'/app/reports/queues',live=root+'/live?queueId=*'
  await page.goto(live)
  assert.equal(await metric('Calls with verified handling user'),'1 of 6')
  assert.equal(await metric('Native booking containment'),'25.00% (1 of 4)')
  assert.equal(await metric('Tracking-source booking conversion'),'50.00% (3 of 6)')
  const handlerGroup=page.getByRole('heading',{name:'Calls by handling user',exact:true}).locator('xpath=following-sibling::ul[1]')
  assert.match(await handlerGroup.innerText(),/Unattributed — 5 calls; 3 answered; 2 missed/)
  assert.ok((await handlerGroup.innerText()).includes(f.handler+' — 1 calls; 1 answered; 0 missed'))
  await proof('call-report-outcomes')
  await f.write('/api/handset/metrics/config',metricConfig('queue-A',0,{startAt:callReportStart,endAt:callReportNow,repeatWindowHours:24}))
  await page.goto(root+'/live?queueId=queue-A')
  assert.equal(await metric('Service level'),'40.00% (2 / 5)')
  for(const call of f.calls)assert.equal(await page.getByRole('link',{name:call.recordId,exact:true}).count(),1)
  assert.match(await page.locator('main').innerText(),/Wait: 5 seconds · Talk 40s · Hold 10s · Wrap 10s · Answered/)
  await proof('call-report-queue-source-legs')
  await page.getByRole('link',{name:f.calls[0].recordId,exact:true}).click()
  await page.getByRole('heading',{name:'Source record',exact:true}).waitFor()
  assert.ok((await page.locator('main').innerText()).includes(f.calls[0].caseId))
  await proof('call-report-queue-source-record')
  await page.goto(live)
  await handlerGroup.getByRole('link',{name:f.handler,exact:true}).click()
  assert.equal(await metric('volume'),'1')
  await page.getByText('Source calls and recovery cases',{exact:true}).click()
  assert.equal(await page.getByRole('link',{name:f.calls[0].recordId,exact:true}).count(),1)
  assert.equal(await page.getByRole('link',{name:f.calls[1].recordId,exact:true}).count(),0)
  await proof('call-report-handling-filter')
  await page.goto(live)
  await page.getByRole('heading',{name:'Calls by tracking source',exact:true}).locator('xpath=following-sibling::ul[1]').getByRole('link',{name:'Winter repairs',exact:true}).click()
  await page.getByLabel('Dashboard name',{exact:true}).fill('Winter repair outcomes')
  const form=page.locator('form[action="/app/reports/queues/dashboards"]')
  for(const group of ['hour','Person (case owner)','number','team','location'])await form.getByLabel(group,{exact:true}).uncheck()
  for(const measure of ['answered','missed'])await form.getByLabel(measure,{exact:true}).uncheck()
  for(const measure of ['contained','converted','Provider service seconds'])await form.getByLabel(measure,{exact:true}).check()
  await click('Save dashboard')
  const dashboardUrl=page.url()
  await page.reload()
  assert.equal(await page.getByLabel('Handling user',{exact:true}).isChecked(),true)
  assert.equal(await page.getByLabel('Tracking source',{exact:true}).isChecked(),true)
  const sourceGroup=page.getByRole('heading',{name:'Calls by tracking source',exact:true}).locator('xpath=following-sibling::ul[1]')
  assert.match(await sourceGroup.innerText(),/Winter repairs — 6 calls; 1 contained; 3 converted; 60 provider service seconds/)
  await proof('call-report-outcome-dashboard')
  await click('Save final report')
  const historyUrl=page.url()
  assert.equal(await metric('Tracking-source booking conversion'),'50.00% (3 of 6)')
  await proof('call-report-outcome-history')
  await page.goto(root+'/groups')
  const assignment=page.locator('form').filter({has:page.getByRole('button',{name:'Save assignment version',exact:true})})
  await assignment.getByLabel('Tracking source',{exact:true}).fill('Spring repairs')
  const newer=await post(runtime,'/api/handset/metrics/groups',{number:'+15125550125',team:'Support',location:'Austin',trackingSource:'Concurrent repairs',revision:1},f.source.headers)
  assert.equal(newer.status,201)
  await click('Save assignment version')
  await page.getByRole('heading',{name:'Review assignment draft',exact:true}).waitFor()
  assert.equal(await page.getByLabel('Tracking source',{exact:true}).inputValue(),'Spring repairs')
  assert.ok((await page.getByText('Compare current assignment',{exact:true}).locator('..').innerText()).includes('Concurrent repairs'))
  await proof('call-report-source-conflict')
  await click('Save reviewed assignment')
  await page.goto(dashboardUrl)
  assert.equal(await metric('volume'),'0')
  assert.equal(await metric('Tracking-source booking conversion'),'Unavailable (zero denominator)')
  await proof('call-report-source-no-matches')
  await page.goto(historyUrl)
  assert.equal(await metric('Tracking-source booking conversion'),'50.00% (3 of 6)')
  assert.match(await sourceGroup.innerText(),/Winter repairs — 6 calls; 1 contained; 3 converted; 60 provider service seconds/)
  await proof('call-report-history-keeps-source')
  await post(runtime,'/auth/operator/status',{operatorId:'synthetic-handset-2',status:'active'},f.source.headers)
  const member=await signIn({...runtime,ownerEmail:'synthetic-handset-2@example.test'})
  await signin(member.cookie);await page.goto(historyUrl)
  await page.getByRole('alert').waitFor();await proof('call-report-outcomes-denied')
 }finally{await runtime.close()}
}
